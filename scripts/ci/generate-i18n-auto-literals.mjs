function replaceByGlossary(value, glossary) {
  let output = value;
  for (const [source, target] of glossary.sort((a, b) => b[0].length - a[0].length)) {
    output = output.split(source).join(target);
  }
  return output;
}

function replaceByPhrases(value, phrases) {
  let output = value;
  for (const [source, target] of phrases) {
    if (!source || !target || source === target) continue;
    output = output.split(source).join(target);
  }
  return output;
}

function cleanupEnglish(value) {
  return value
    .replace(/（/g, ' (')
    .replace(/）/g, ')')
    .replace(/，/g, ', ')
    .replace(/。/g, '.')
    .replace(/：/g, ': ')
    .replace(/；/g, '; ')
    .replace(/、/g, ' / ')
    .replace(/·/g, ' · ')
    .replace(/\s+/g, ' ')
    .trim();
}

function translate(text, targetLang) {
  const exact = targetLang === 'lo' ? exactLo : exactEn;
  const phrases = targetLang === 'lo' ? phraseLo : phraseEn;
  if (exact.has(text) && !hasChinese(exact.get(text))) return exact.get(text);
  let output = replaceByGlossary(text, enGlossary);
  if (hasChinese(output)) output = replaceByPhrases(output, phrases);
  if (hasChinese(output)) output = replaceByGlossary(output, enGlossary);
  output = cleanupEnglish(output);
  if (hasChinese(output)) {
    const fallback = exactEn.get(text);
    if (fallback && !hasChinese(fallback)) return fallback;
    return `Localized UI text ${keyFor(text).replace('auto.literal.', '')}`;
  }
  return output || `Localized UI text ${keyFor(text).replace('auto.literal.', '')}`;
}

