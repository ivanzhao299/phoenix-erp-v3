const findings = audit.findings || [];
const uniqueTexts = [...new Set(findings.map((item) => normalize(item.text)).filter(Boolean))]
  .filter((text) => hasChinese(text));

function buildExactMap(target) {
  const map = new Map();
  for (const [key, source] of Object.entries(zh)) {
    const zhText = normalize(source);
    const targetText = normalize(target[key]);
    if (!zhText || !targetText || !hasChinese(zhText)) continue;
    if (!map.has(zhText)) map.set(zhText, targetText);
  }
  return map;
}

function buildPhraseList(target) {
  return [...buildExactMap(target).entries()]
    .filter(([source, translated]) => source.length >= 2 && translated && source !== translated)
    .sort((a, b) => b[0].length - a[0].length);
}

