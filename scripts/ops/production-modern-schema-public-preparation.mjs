/** Fixed public failure vocabulary. Never pass through an exception string. */
const stages = new Set('BOOTSTRAP FLOOR HOST_SURFACE PLAN BACKUP REHEARSAL HISTORICAL_AUDIT UNSPECIFIED'.split(' '));
const hostReasons = new Map();
for (const [prefix, reasons] of [
  ['MODERN_SCHEMA_EXECUTORS_HOLD', `SURFACE_OBSERVATION_UNAVAILABLE CONTAINER_IDENTITY_REQUIRED EXACT_THREE_RUNTIME_PINS_REQUIRED
    RUNTIME_MOVED_BEFORE_STOP SINGLE_IPV4_RUNTIME_NETWORK_REQUIRED EXCLUSIVE_THREE_MEMBER_NETWORK_REQUIRED RUNTIME_NETWORK_CHANGED
    EXCLUSIVE_LOOPBACK_DATABASE_AND_API_PORTS_REQUIRED EXACT_BRIDGE_REQUIRED UNFENCED_NONLOOPBACK_IPV6 REVIEWED_HOST_OWNERSHIP_UNAVAILABLE
    SHARED_OR_UNMANAGED_CONTAINER_EXECUTOR CONTAINER_PID_NAMESPACE_UNOBSERVABLE HISTORICAL_MIGRATOR_SOURCE_UNVERIFIED
    OWNED_REHEARSAL_ISOLATION_CHANGED OWNED_REHEARSAL_STORAGE_CHANGED OWNED_REHEARSAL_RUNTIME_CHANGED OWNED_REHEARSAL_MOUNTS_CHANGED
    AUXILIARY_ERP_CONTAINER_UNACCOUNTED FOREIGN_CONTAINER_IDENTITY_CHANGED FOREIGN_CONTAINER_OWNERSHIP_UNVERIFIED
    LOCAL_DATABASE_OR_ERP_SCHEDULER_UNACCOUNTED HOST_PROCESS_IDENTITY_UNREADABLE AUXILIARY_HOST_ERP_EXECUTOR_UNACCOUNTED
    HOST_EXECUTOR_OWNERSHIP_UNVERIFIED COMPLETE_DATABASE_VISIBILITY_REQUIRED UNKNOWN_OR_CROSS_DATABASE_CLIENT
    ORIGINAL_CONTROL_LEASE_REQUIRED ORIGINAL_PRIMARY_IDENTITY_CHANGED NATIVE_MIGRATION_BACKEND_REQUIRED NATIVE_CONTROLLED_CANDIDATE_REQUIRED
    EXACT_OWNED_READONLY_SESSION_REQUIRED ORIGINAL_CONTROL_SESSION_MISSING ORIGINAL_API_DATABASE_SESSIONS_REMAIN
    UNKNOWN_OR_NEW_DATABASE_EXECUTOR UNKNOWN_DATABASE_APPLY_OR_EXTENSION_WORKER RETAINED_INVENTORY_UNVERIFIED RETAINED_INVENTORY_OWNER_REUSED`],
  ['MAINTENANCE_HOLD', `ROOT_READER_BOUNDED_READ_FAILED ROOT_READER_MODERN_PROCESS_VISIBILITY_REQUIRED ROOT_READER_PROCESS_REUSED
    ROOT_READER_CONTAINER_ID ROOT_READER_CONTAINER_CHANGED ROOT_READER_UNIT_INVENTORY ROOT_READER_SCHEDULER_FILE_UNVERIFIED ROOT_READER_SCHEDULER_CHANGED
    ROOT_READER_UNIT_DEFINITION ROOT_READER_SYSTEMD_EXEC_DEFINITION_FORMAT ROOT_READER_SYSTEMD_TYPED_EXEC_UNVERIFIED
    ROOT_READER_SYSTEMD_TYPED_EXEC_FORMAT ROOT_READER_EXTERNAL_ORCHESTRATOR_REQUIRES_REGISTRY ROOT_READER_VENDOR_UNVERIFIED
    ROOT_READER_VENDOR_CONTEXT ROOT_READER_VENDOR_LINK ROOT_READER_VENDOR_PARENT ROOT_READER_VENDOR_ACL ROOT_READER_VENDOR_TARGET ROOT_READER_VENDOR_CHANGED`],
]) {
  for (const reason of reasons.split(/\s+/)) hostReasons.set(prefix + '=' + reason, 'HOST_SURFACE_' + reason);
}
const publicFailures = new Set([...stages, ...hostReasons.values(), 'HOST_SURFACE_UNCLASSIFIED']);

export function publicModernSchemaPreparationFailure(stage, error) {
  if (stage === 'HOST_SURFACE') return hostReasons.get(error?.message) ?? 'HOST_SURFACE_UNCLASSIFIED';
  return stages.has(stage) ? stage : 'UNSPECIFIED';
}

export function isFailedModernSchemaPreparation(value, {owner, targetSha}) {
  return value && Object.getPrototypeOf(value) === Object.prototype &&
    Object.keys(value).sort().join(',') === 'failure,owner,prepared,schema,targetSha' &&
    value.schema === 'phoenix.modern-schema-public-preparation-hold/v1' &&
    value.owner === owner && value.targetSha === targetSha && value.prepared === false &&
    publicFailures.has(value.failure);
}
