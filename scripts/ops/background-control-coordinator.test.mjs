test('each FENCE publication crash point stays denied and cannot manufacture drain readiness', () => {
  for (const point of ['intent', 'projection', 'final-ledger']) {
    const f = fixture(); const writePrivate = f.publisher.writePrivate, writePublic = f.publisher.writePublic; let writes = 0;
    f.publisher.writePrivate = value => { writes++; if ((point === 'intent' && writes === 1) || (point === 'final-ledger' && writes === 2)) throw new Error('fixture crash'); writePrivate(value); };
    f.publisher.writePublic = value => { if (point === 'projection') throw new Error('fixture crash'); writePublic(value); };
    assert.throws(() => f.publisher.fence(binding, [p]), /fixture crash/);
    assert.notEqual(f.manifest?.phase, 'OPEN');
    if (point !== 'intent') assert.throws(() => f.publisher.fence({ ...binding, owner: '999-1' }, [p]), /UNFINISHED_BACKGROUND_TRANSACTION/);
  }
});
test('OPEN authority ledger and exact projection digest commit before public admissions resume', async () => {
  const f = fixture(); f.publisher.fence(binding, [p]); await f.publisher.open(binding, [next], async () => true);
  assert.equal(f.record.phase, 'OPEN'); assert.match(f.record.manifestDigest, /^[a-f0-9]{64}$/);
  assert.ok(f.events.indexOf('private:OPEN') < f.events.indexOf('public:OPEN'));
});
test('OPEN private-commit failure cannot publish OPEN; public-publish failure after commit requires manual reconciliation', async () => {
  for (const point of ['authority', 'projection']) {
    const f = fixture(); f.publisher.fence(binding, [p]);
    const writePrivate = f.publisher.writePrivate, writePublic = f.publisher.writePublic;
    f.publisher.writePrivate = value => { if (point === 'authority' && value.phase === 'OPEN') throw new Error('fixture crash'); writePrivate(value); };
    f.publisher.writePublic = value => { if (point === 'projection' && value.phase === 'OPEN') throw new Error('fixture crash'); writePublic(value); };
    await assert.rejects(f.publisher.open(binding, [next], async () => true), /fixture crash/);
    assert.equal(f.manifest.phase, 'FENCED'); assert.equal(f.record.phase, point === 'authority' ? 'FENCED' : 'OPEN');
    assert.throws(() => f.publisher.fence({ ...binding, owner: '999-1' }, [p]), point === 'authority' ? /UNFINISHED_BACKGROUND_TRANSACTION/ : /UNRECONCILED_PUBLIC_STATE/);
  }
});
