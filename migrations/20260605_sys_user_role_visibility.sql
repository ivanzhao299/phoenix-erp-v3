-- ═════════════════════════════════════════════════════════════════════════════
-- sys_user_role.is_visible — 角色显示开关（纯显示层）
-- ═════════════════════════════════════════════════════════════════════════════
-- 背景：部分用户被授予某角色仅是为了权限组合（如出纳为了访问现金账户），并非
-- 实际职务。前台显示"宋明光 · 出纳"会引起误会。
--
-- 本字段控制"该绑定是否在前台显示角色名"，**不影响**：
--   · 任何菜单/CRUD/审批权限
--   · DataScope 计算
--   · 角色绑定本身
--
-- DEFAULT true：原有绑定均默认可见，与现状一致。
-- ═════════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE sys_user_role
  ADD COLUMN IF NOT EXISTS is_visible BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN sys_user_role.is_visible IS '前台是否显示该角色名（纯显示，不影响权限）';

COMMIT;
